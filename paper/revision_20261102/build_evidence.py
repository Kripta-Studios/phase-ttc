"""Generate manuscript tables from versioned research receipts, without training.

Run with ``python -S paper/revision_20261102/build_evidence.py`` from any directory.
The copied evidence makes the generated tables reproducible in a source archive.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SOURCES = {
    "official": "paper/data/official_benchmark.json",
    "adapt": "docs/research_progress_20261101/v1/evidence/evaluator_audit.json",
    "canonical": "docs/research_log_canonical_population2608/evidence/report.json",
    "jepa": "docs/jepa_closure_20261031/closure_analysis.json",
}


def read_sources() -> tuple[dict[str, Any], dict[str, Any]]:
    """Copy exact source bytes, or read the bundled copy outside the repository."""
    data: dict[str, Any] = {}
    manifest: dict[str, Any] = {}
    previous_path = HERE / "source_manifest.json"
    previous = json.loads(previous_path.read_text()) if previous_path.exists() else {}
    (HERE / "evidence").mkdir(exist_ok=True)
    for key, relative in SOURCES.items():
        source = ROOT / relative
        bundled = HERE / "evidence" / f"{key}.json"
        payload = bundled.read_bytes() if bundled.is_file() else source.read_bytes()
        if key in previous and hashlib.sha256(payload).hexdigest() != previous[key]["sha256"]:
            raise ValueError(f"Bundled evidence hash changed: {key}")
        bundled.write_bytes(payload)
        data[key] = json.loads(payload.decode("utf-8-sig"))
        manifest[key] = {
            "repository_source": relative,
            "bundled_source": f"evidence/{key}.json",
            "sha256": hashlib.sha256(payload).hexdigest(),
            "bytes": len(payload),
        }
    return data, manifest


def table(
    command: str, caption: str, label: str, columns: str, header: str, rows: list[str]
) -> str:
    """Return a LaTeX command containing a table with generated numeric rows."""
    environment = "table*" if len(columns) > 3 else "table"
    return (
        "\\newcommand{\\" + command + "}{%\n"
        "\\begin{" + environment + "}[t]\n\\centering\\small\n"
        "\\caption{" + caption + "}\n\\label{" + label + "}\n"
        "\\begin{tabular}{"
        + columns
        + "}\n\\toprule\n"
        + header
        + " \\\\\n\\midrule\n"
        + "\n".join(row + " \\\\" for row in rows)
        + "\n\\bottomrule\n\\end{tabular}\n\\end{"
        + environment
        + "}%\n}\n"
    )


def main() -> None:
    """Validate receipts and create tables, values, and a source hash manifest."""
    data, manifest = read_sources()
    official = data["official"]
    phase = official["phase_submission"]["metrics"]
    competitor = official["competitor"]["metrics"]
    weighted = sum(phase[k] * w for k, w in official["benchmark"]["band_weights"].items())
    if abs(weighted - phase["overall_MiD"]) > 1e-10:
        raise ValueError("Official overall score does not equal its weighted components")
    audit = data["adapt"]
    if audit["rows"] != 434 or audit["official_equivalence"]:
        raise ValueError("Expected corrected 434-row local audit with unresolved equivalence")
    canonical = data["canonical"]["routes"]["F0"]
    jepa = data["jepa"]
    values: dict[str, Any] = {
        "official": {
            "as_of": official["as_of"],
            "phase": phase,
            "competitor": competitor,
            "recomputed_overall": weighted,
        },
        "adapt": {},
        "canonical": {"domains": {}, "road_bootstrap": canonical["road_bootstrap"]},
        "jepa": {
            "primary_mae": jepa["primary_mae"],
            "primary_comparisons": jepa["primary_comparisons"],
            "latent_comparisons": jepa["latent_comparisons"],
            "primary_benefit_gate_passed": jepa["primary_benefit_gate_passed"],
        },
    }
    latex = "% Generated by build_evidence.py; numeric entries come from bundled JSON receipts.\n"
    latex += table(
        "EvidenceOfficialTable",
        "Archived official GarlTTC Test scores (28 October 2026; lower is better). "
        "The PHASE-TTC row concerns the frozen TRAIN40 system, not the later adaptation. "
        "Both submissions cover 6,762 scored tokens with zero reported failures. "
        "The competitor values retain the published two-decimal precision.",
        "tab:official",
        "lrrrrr",
        "Method & Overall & Crucial & Small & Large & Negative",
        [
            name
            + " & "
            + " & ".join(
                f"{metrics[k]:.2f}" for k in ("overall_MiD", "MiDc", "MiDs", "MiDl", "MiDn")
            )
            for name, metrics in [("PHASE-TTC", phase), ("Garl-TTC", competitor)]
        ],
    )
    rows = []
    populations = [
        ("All queries", "all434_public_diagnostic"),
        ("Road", "road365"),
        ("Excluding Slider-750", "pdf_reproduced_sequences383"),
        ("Slider-750", "Slider-750"),
    ]
    for name, key in populations:
        d = audit["frozen_baseline_metrics"][key]
        original = d["original_email_processed"]
        adapted = d["frozen_submission_email_processed"]
        values["adapt"][key] = {
            "original": original,
            "adapted": adapted,
            "mae_reduction_pct": 100 * (1 - adapted["mae_seconds"] / original["mae_seconds"]),
            "rae_reduction_pct": 100
            * (1 - adapted["relative_error_pct"] / original["relative_error_pct"]),
        }
        rows.append(
            f"{name} & {original['scored']} & {original['mae_seconds']:.4f} & "
            f"{adapted['mae_seconds']:.4f} & {original['relative_error_pct']:.3f} & "
            f"{adapted['relative_error_pct']:.3f}"
        )
    latex += table(
        "EvidenceAdaptTable",
        "Corrected local EvTTC comparison on historically exposed data. MAE is in seconds; "
        "RAE is a percentage. Both columns apply the organizer-described interpolation of "
        "negative predictions for scoring only. These are query-weighted local scores, not "
        "new official results. Slider-750 remains unresolved against the organizer's score.",
        "tab:adapt",
        "lrrrrr",
        "Population & $n$ & MAE orig. & MAE adapt. & RAE orig. & RAE adapt.",
        rows,
    )
    rows = []
    for name, key in [("Road", "road"), ("Slider-500", "slider")]:
        d = canonical["domains"][key]
        values["canonical"]["domains"][key] = {k: v for k, v in d.items() if k != "by_recording"}
        original, corrected = d["original"], d["canonical"]
        rows.append(
            f"{name} & {d['paired']}/{d['population']} & "
            f"{original['mae_seconds']:.6f} & {corrected['mae_seconds']:.6f} & "
            f"{original['relative_error_pct']:.4f} & {corrected['relative_error_pct']:.4f}"
        )
    ci = canonical["road_bootstrap"]["mae_seconds"]["ci95"]
    latex += table(
        "EvidenceCanonicalTable",
        "Frozen F0 with canonical PAIR timing on the exposed development population. "
        "Metrics average recordings equally within each domain; availability is explicit. "
        f"Road $\\Delta$MAE has a descriptive 95\\% recording-bootstrap interval "
        f"$[{ci[0]:.7f}, {ci[1]:.7f}]$ s. Slider-500 is one previously used recording.",
        "tab:canonical",
        "lrrrrr",
        "Domain & Paired/all & MAE orig. & MAE canon. & RAE orig. & RAE canon.",
        rows,
    )
    rows = [
        name + f" & {jepa['primary_mae'][key]:.8f}"
        for name, key in [
            ("Static distillation", "B_static"),
            ("One-step prediction", "C_one_step"),
            ("Shuffled future", "C_shuffle"),
            ("Random initialization", "random_init"),
        ]
    ]
    latex += table(
        "EvidenceJepaTable",
        "Frozen-encoder probe after the fixed-teacher pilot, averaged over seeds 7, 13, and 21. "
        "The target is annotated log-height change (dimensionless), not TTC in seconds. "
        "A ridge probe fits 512 samples from 24 sequences and evaluates 256 samples from "
        "eight other, historically exposed sequences. "
        "Neither prespecified superiority test passes.",
        "tab:jepa",
        "lr",
        "Training arm & Probe MAE",
        rows,
    )
    for command, number, precision in [
        ("evOfficialOverall", phase["overall_MiD"], 4),
        (
            "evAdaptMAEOriginal",
            values["adapt"]["all434_public_diagnostic"]["original"]["mae_seconds"],
            4,
        ),
        ("evAdaptMAENew", values["adapt"]["all434_public_diagnostic"]["adapted"]["mae_seconds"], 4),
        (
            "evAdaptRAEOriginal",
            values["adapt"]["all434_public_diagnostic"]["original"]["relative_error_pct"],
            3,
        ),
        (
            "evAdaptRAENew",
            values["adapt"]["all434_public_diagnostic"]["adapted"]["relative_error_pct"],
            3,
        ),
        (
            "evSliderCadenceReduction",
            100
            * (
                1
                - canonical["domains"]["slider"]["canonical"]["mae_seconds"]
                / canonical["domains"]["slider"]["original"]["mae_seconds"]
            ),
            2,
        ),
    ]:
        latex += f"\\newcommand{{\\{command}}}{{{number:.{precision}f}}}\n"
    (HERE / "evidence_tables.tex").write_text(latex, encoding="utf-8", newline="\n")
    (HERE / "evidence_values.json").write_text(
        json.dumps(values, indent=2, ensure_ascii=True) + "\n", encoding="utf-8", newline="\n"
    )
    manifest["generator"] = {
        "file": "build_evidence.py",
        "sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    (HERE / "source_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=True) + "\n", encoding="utf-8", newline="\n"
    )
    print(
        "Generated four evidence tables; verified weighted official score "
        "and corrected local audit."
    )


if __name__ == "__main__":
    main()
